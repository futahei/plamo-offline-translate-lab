export const SAMPLE_LANGUAGES = Object.freeze(['ja', 'en', 'zh', 'ko', 'fr', 'de', 'es']);
export const SAMPLE_SENTENCES = Object.freeze(Object.fromEntries(
  SAMPLE_LANGUAGES.map((lang) => [lang, Object.freeze(SENTENCES.map((row) => row[lang]))]),
));

export function pickSample(sourceLang, targetLang = 'ja', previousText = '', random = Math.random) {
  const supported = sourceLang === 'auto'
    ? SAMPLE_LANGUAGES.filter((lang) => lang !== targetLang)
    : [sourceLang];
  const languages = supported.filter((lang) => SAMPLE_SENTENCES[lang]?.length);
  if (!languages.length) throw new Error('この言語の例文はありません。');

  const language = languages[Math.min(languages.length - 1, Math.floor(random() * languages.length))];
  const samples = SAMPLE_SENTENCES[language];
  let index = Math.min(samples.length - 1, Math.floor(random() * samples.length));
  if (samples[index] === previousText) index = (index + 1) % samples.length;
  return { language, text: samples[index] };
}
